// Joins every migration into one file, for setting up a new database
// (production, or a replacement) in a single paste. Run:
//   node scripts/combine-migrations.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const parts = files.map((f) => `-- =====================================================================\n-- ${f}\n-- =====================================================================\n\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
const header = `-- Tablekeep: every migration in order (${files.length} files).\n-- Generated by scripts/combine-migrations.mjs. Don't edit by hand.\n-- Paste into Supabase -> SQL Editor -> New query on a NEW project and Run.\n\n`;
writeFileSync("supabase/all-migrations.sql", header + parts.join("\n"));
console.log(`Wrote supabase/all-migrations.sql from ${files.length} migrations: ${files.join(", ")}`);
